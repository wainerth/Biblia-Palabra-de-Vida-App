      utc,
      gmt,
    ];
  }

  // Método para buscar por ciudad
  static String? findTimeZoneByCity(String cityName) {
    final allZones = getAllTimeZones();
    final searchTerm = cityName.toLowerCase().replaceAll(' ', '_');
    
    return allZones.firstWhere(
      (zone) => zone.toLowerCase().contains(searchTerm),
      orElse: () => utc,
    );
  }

